#!/usr/bin/env python3
"""Browser/maths QA at both approved screen widths; actual Chromium screenshots."""
import json,sys
from pathlib import Path
from playwright.sync_api import sync_playwright
R=Path(__file__).resolve().parents[1];HTML=R/'F4/F4-08-algebra-bar.html';SHOTS=R/'shots/F4-08';SHOTS.mkdir(parents=True,exist_ok=True)
checks=[]
def check(name,ok,detail=''):
 ok=bool(ok);checks.append({'name':name,'passed':ok,'detail':detail})
 if not ok:print('FAIL',name,str(detail)[:250],flush=True)
def mode(page,name):page.get_by_role('tab',name=name.capitalize()).click();page.wait_for_timeout(80)
def fill(page,label,value):
 item=page.locator(f'#F4-08 input[aria-label="{label}"]');item.fill(str(value));item.press('Tab')
def add(page,n,b):
 for _ in range(n):page.get_by_role('button',name='+ x part').click()
 page.get_by_role('button',name=f'+ known {b}').click()
def feedback(page):return page.locator('#F4-08 .f408-status').inner_text()
with sync_playwright() as playwright:
 browser=playwright.chromium.launch(headless=True,executable_path='/usr/bin/chromium',args=['--no-sandbox','--disable-dev-shm-usage'])
 for width in (380,1280):
  page=browser.new_page(viewport={'width':width,'height':1000},reduced_motion='reduce');errors=[]
  page.on('pageerror',lambda e: errors.append(str(e)))
  page.set_content(HTML.read_text(),wait_until='load',timeout=60000)
  vals=page.evaluate('''()=>{const M=window.F408_MATH;let a=M.solve({n:3,b:5,total:26}),b=M.solve({n:2,b:5,total:19});return {a,b,terms:M.terms({n:2,b:5,total:19}),math:M.checkMath({n:3,b:5,total:26},{count:3,known:true,balanced:true,divided:true,remaining:21,x:7,slots:[]}),bad:M.checkMath({n:3,b:5,total:26},{count:3,known:true,balanced:true,divided:true,remaining:21,x:21,slots:[]})}}''')
  check(f'{width} correct first remainder',vals['a']['remainder']==21)
  check(f'{width} correct first x',vals['a']['x']==7)
  check(f'{width} translator remainder',vals['b']['remainder']==14)
  check(f'{width} translator x',vals['b']['x']==7)
  check(f'{width} translator term order',vals['terms']==['2x','+ 5','= 19'])
  check(f'{width} maths correct model accepted',vals['math']['ok'])
  check(f'{width} misconception x=21 rejected',not vals['bad']['ok'])
  for mode_name in ['watch','guided','explore','challenge']:
   mode(page,mode_name)
   check(f'{width} {mode_name} one SVG',page.locator('#F4-08 svg.f408-svg').count()==1)
   check(f'{width} {mode_name} mascot dock',page.locator('#F4-08 .nv-dock').count()==1)
   check(f'{width} {mode_name} three information cards',page.locator('#F4-08 .f408-card-v').count()==3)
   check(f'{width} {mode_name} no horizontal overflow',page.evaluate('document.documentElement.scrollWidth<=window.innerWidth'))
   check(f'{width} {mode_name} no placeholder fraction',page.locator('#F4-08 .nv-frac-tbd').count()==0)
   check(f'{width} {mode_name} no JS errors',not errors,errors[-2:])
   path=SHOTS/f'F4-08-{width}-{mode_name}.png';page.locator('#F4-08').screenshot(path=str(path),animations='disabled',timeout=25000)
   check(f'{width} {mode_name} screenshot',path.stat().st_size>6000)
  # expression must not leak fabricated total or solve x: real model, not decoration
  check(f'{width} challenge expression no null leaked','null' not in page.locator('#F4-08 svg.f408-svg').text_content())
  page.get_by_role('button',name='Check my proof').click()
  check(f'{width} empty expression model rejected','equal unknown x-parts' in feedback(page))
  add(page,2,4);fill(page,'Algebraic expression','2x + 5');page.get_by_role('button',name='Check my proof').click()
  check(f'{width} wrong expression fails','add the known 4' in feedback(page).lower(),feedback(page))
  fill(page,'Algebraic expression','2x + 4');page.get_by_role('button',name='Check my proof').click()
  check(f'{width} expression challenge solved','Correct: 2 equal x-parts' in feedback(page),feedback(page))
  check(f'{width} expression completed without null','null' not in page.locator('#F4-08 svg.f408-svg').text_content())
  check(f'{width} expression keeps two x tiles',page.locator('#F4-08 svg.f408-svg .f408-tile[data-type="x"]').count()==2)
  page.get_by_role('button',name='Next problem →').click()
  add(page,3,5);page.get_by_role('button',name='Check my proof').click()
  check(f'{width} balance step required','balanced subtraction' in feedback(page).lower(),feedback(page))
  page.get_by_role('button',name='Subtract knowns on BOTH sides').click()
  fill(page,'Remainder','26');page.get_by_role('button',name='Divide into x-parts').click()
  check(f'{width} invalid remainder blocks division','correct remainder' in feedback(page))
  fill(page,'Remainder','21');page.get_by_role('button',name='Divide into x-parts').click()
  fill(page,'Value of x','21');page.get_by_role('button',name='Check my proof').click()
  check(f'{width} wrong x rejected','Find ONE part' in feedback(page),feedback(page))
  fill(page,'Value of x','7');page.get_by_role('button',name='Check my proof').click()
  check(f'{width} equation challenge proved','Proved: 3 × 7 + 5 = 26' in feedback(page),feedback(page))
  check(f'{width} solved tiles show 7',page.locator('#F4-08 svg.f408-svg .f408-tile[data-type="x"]').count()==3 and '7' in page.locator('#F4-08 svg.f408-svg').text_content())
  page.get_by_role('button',name='Next problem →').click()
  add(page,2,5);page.get_by_role('button',name='Subtract knowns on BOTH sides').click()
  fill(page,'Remainder','14');page.get_by_role('button',name='Divide into x-parts').click();fill(page,'Value of x','7')
  page.get_by_role('button',name='Check my proof').click()
  check(f'{width} translator requires equation slots','Match every part of the bar' in feedback(page),feedback(page))
  page.get_by_role('button',name='Arrange equation terms').click();page.get_by_role('button',name='Check my proof').click()
  check(f'{width} F4-10 solved','Proved: 2 × 7 + 5 = 19' in feedback(page),feedback(page))
  page.get_by_role('button',name='Finish challenges →').click()
  check(f'{width} completed 3 challenges',page.locator('#F4-08 .f408-done').count()>0)
  mode(page,'explore');choose=page.locator('#F4-08 select[aria-label="Choose algebra preset"]')
  check(f'{width} explore presets 3',choose.locator('option').count()==3)
  choose.select_option('Y7-034');add(page,2,4);check(f'{width} expression preset 2 x tiles',page.locator('#F4-08 svg.f408-svg').get_attribute('data-count')=='2')
  page.locator('#F4-08 .f408-tile[data-type="x"]').first.focus();page.keyboard.press('Delete')
  check(f'{width} keyboard Delete actually removes',page.locator('#F4-08 svg.f408-svg').get_attribute('data-count')=='1')
  page.locator('#F4-08 .f408-supply[data-supply="x"]').focus();page.keyboard.press('Enter')
  check(f'{width} keyboard Enter actually adds',page.locator('#F4-08 svg.f408-svg').get_attribute('data-count')=='2')
  choose=page.locator('#F4-08 select[aria-label="Choose algebra preset"]');choose.select_option('F4-10')
  check(f'{width} F4-10 is a preset',page.locator('#F4-08 svg.f408-svg .f408-eqslot').count()==0 and page.locator('#F4-08 svg.f408-svg').get_attribute('data-mode')=='explore')
  check(f'{width} no JS errors after all checks',not errors,errors[-3:])
  page.close()
 browser.close()
report={'total':len(checks),'passed':sum(c['passed'] for c in checks),'failed':sum(not c['passed'] for c in checks),'checks':checks}
(R/'tests/F4-08-BROWSER-RESULTS.json').write_text(json.dumps(report,indent=2))
print('F4-08 BROWSER',report['passed'],'/',report['total'],'failures',report['failed'],flush=True)
sys.exit(bool(report['failed']))
