ROOT = Path(__file__).resolve().parents[1]
CANON = ROOT / '00-master' / 'nova-master.html'
REDIRECT = ROOT / '00-master' / 'nova-master-updated.html'
PORTABLE = ROOT / '00-master' / 'NOVA-MASTER-FOR-OTHER-AI.md'
OLD_HANDOVER = ROOT / 'HANDOVER-v3.md'
MARKER = 'NOVA-REPAIR-2026-10-11-CANONICAL-v1'
# SHA1 values from the exact GitHub tree audited on 11 October 2026.
BASE_GIT_BLOBS = {
  CANON.relative_to(ROOT).as_posix(): '3183ab3bcc64d92967b54d0354a2119f120000d6',
  REDIRECT.relative_to(ROOT).as_posix(): '088f14cb8ecfb054ea286dc024f3bc39e834e40e',
  PORTABLE.relative_to(ROOT).as_posix(): 'b360f1e6aecfdfafb4b550062732311670939fd4',
  OLD_HANDOVER.relative_to(ROOT).as_posix(): 'c978d450b2613df99c294cbbd9bc69764f296f69',
}

def git_blob_sha(data: bytes) -> str:
    return hashlib.sha1(f'blob {len(data)}\0'.encode('ascii') + data).hexdigest()

def assert_baseline():
    for rel, expected in BASE_GIT_BLOBS.items():
        file = ROOT / rel
        if not file.exists():
            raise RuntimeError(f'Missing expected file: {file}')
        b = file.read_bytes()
        if rel == CANON.relative_to(ROOT).as_posix() and MARKER in b.decode('utf-8'):
            raise RuntimeError('Already applied: canonical master contains repair marker. Use the sync/check tools, not this installer again.')
        actual = git_blob_sha(b)
        if actual != expected:
            raise RuntimeError(f'Your {rel} has changed since the audited GitHub push. Refusing to overwrite your local edits.\nExpected Git blob {expected}\nFound Git blob    {actual}')

def repair_master(s: str) -> str:
    if '<script>var D=' not in s or 'function pc(id)' not in s:
        raise RuntimeError('Master format changed; cannot apply a safe anchored repair')
    # Explicit owner approval, 10 Oct 2026: proper numerator/bar/denominator, NOVA chalk.
    locked_html = ('<li><b>Fractions:</b> LOCKED — use traditional stacked fractions: '
      'NOVA Chalk numerator above a full horizontal fraction bar above the NOVA Chalk denominator. '
      'Use <code>NOVA.mt.render</code> for HTML maths, or <code>NOVA.chalkText</code> plus '
      '<code>NOVA.neonLine</code> for SVG mathematical evidence. Inline n/d is permitted only '
      'in compact controls. Do not use fraction-TBD placeholders. The owner decision is '
      'recorded in <code>F5/F5-FRACTION-NOTATION-LOCK.md</code>.</li>')
    s, n = re.subn(r'<li><b>Fractions:</b>.*?</li>', lambda _: locked_html, s, count=1, flags=re.DOTALL)
    if n != 1: raise RuntimeError('Expected styled fraction rule not found')
    s, n = re.subn(r'<li>Fractions: neutral placeholder tagged .*?</li>',
      lambda _: '<li>Fractions: traditional stacked NOVA Chalk numerator/bar/denominator notation (owner-locked). No neutral placeholders.</li>',
      s, count=1, flags=re.DOTALL)
    if n != 1: raise RuntimeError('Expected old F0 fraction rule not found')
    # Old normative instructions in the automatically copied run-standard text.
    replacements = {
        "fractions stay a neutral placeholder tagged 'fraction design TBD' until the fraction design is decided.":
          'fractions MUST use the owner-locked traditional NOVA Chalk stacked numerator / horizontal bar / denominator; no TBD fraction placeholders.',
        "every fraction value uses the core placeholder (.nv-frac-tbd tagged 'fraction design TBD'); never a raw '3/4' string on stage.":
          'every teaching-stage fraction is a proper stacked numerator above a horizontal fraction bar above a denominator, all in NOVA Chalk. Do not emit neutral or TBD placeholders; inline n/d is limited to space-constrained controls.',
        'Source data is prompts/specs/s1-s6.py plus guard.txt, generated by prompts/specs/gen.py into specs.json and the SPEC block in this file. Re-run gen.py after any edit.':
          'The canonical SPEC object is embedded in this HTML. prompts/specs/gen.py extracts its exact data into specs.json. Historical s1–s6 sources are absent from this checkout and are NOT required to rebuild the derived JSON.',
        'assets/helpers/pip/pack80/': 'core-native Pip helper poses (see assets/helpers/registry.json)',
        'assets/helpers/nova-cat/pack60/': 'core-native Nova helper poses (see assets/helpers/registry.json)',
        'assets/helpers/teen/': 'core-native Izaac helper poses (see assets/helpers/registry.json)',
        'assets/helpers/izaac/': 'core-native Izaac helper poses (see assets/helpers/registry.json)',
    }
    for old, new in replacements.items():
        if old in s: s = s.replace(old, new)
    # Make the portable prompt's static standard always reflect the locks.
    prefix = ("LOCKED PRODUCTION OVERRIDES (owner-approved 2026-10-10): "
       "every maths fraction uses properly stacked NOVA Chalk numerator above horizontal fraction bar above denominator; "
       "never render fraction TBD placeholders. Draw maths only with the established NOVA core primitives and approved house colours. "
       "Native mascot art and pose selection come from NOVA.scene.helperStrip / NOVA.helperImg, "
       "not absent external helper pack paths. No changes to the approved F0 core are authorised.\\n\\n")
    s, n = re.subn(r'var STD="Standards: ', lambda _: 'var STD="'+prefix+'Standards: ', s, count=1)
    if n != 1: raise RuntimeError('Cannot locate shared standard declaration')
    banner = (f'<!-- {MARKER} -->'
      '<section id="governance-2026-10-11" class="nova-card" style="border-color:#2bdcf3">'
      '<h3>Production authority — 11 October 2026</h3>'
      '<p><b>ONE editable master:</b> <code>00-master/nova-master.html</code>. '
      '<code>nova-master-updated.html</code> is a redirect; the portable Markdown is generated with '
      '<code>node tools/export_master_prompts.js</code>, carrying the source SHA-256.</p>'
      '<p><b>Fractions:</b> locked traditional stacked mathematical fractions in NOVA Chalk (numerator / horizontal bar / denominator). '
      'The earlier fraction-TBD wording has been superseded, not reopened.</p>'
      '<p><b>Helpers:</b> use core-native Pip, Nova and Izaac positions/poses; the undocumented pack80/pack60 external folders are not prerequisites. '
      'See <code>assets/helpers/registry.json</code> and <code>docs/PRODUCTION-SOURCE-MAP.md</code>.</p>'
      '<p><b>Core integration:</b> any missing numbered-line, drag or motion API is a reconciliation/QA gate, '
      'not permission to replace the shared F0 core. See <code>docs/CORE-INTEGRATION-GATE.md</code>.</p>'
      '</section>')
    anchor = '<section id="f0-lessons">'
    if anchor not in s: raise RuntimeError('Cannot locate canonical F0 section for governance banner')
    s = s.replace(anchor, banner+anchor, 1)
    # Guard against any old normative TBD instruction that may have changed punctuation.
    leftover = [m.start() for m in re.finditer(r'fraction design TBD|nv-frac-tbd', s, flags=re.IGNORECASE)]
    if leftover:
        # In this planning-only file these tokens must never be presented as current instructions.
        s = re.sub(r'fraction design TBD', 'obsolete fraction placeholder (superseded by stacked NOVA Chalk)', s, flags=re.IGNORECASE)
        s = s.replace('nv-frac-tbd', 'obsolete-fraction-placeholder-not-for-use')
    if MARKER not in s or 'F5/F5-FRACTION-NOTATION-LOCK.md' not in s:
        raise RuntimeError('Required governance lock is absent after patch')
    return s

HIST_BANNER = ('<!-- HISTORICAL RUN NOTE: The current production authority is '
               '00-master/nova-master.html and HANDOVER-v4.md (11 October 2026). '
               'Old statements that a build was not yet on GitHub describe the original ZIP delivery only. '
               'Owner review/GOLD status must be rechecked; this file is retained for provenance. -->\n\n')

def historic_note(s: str) -> str:
    return s if s.startswith('<!-- HISTORICAL RUN NOTE:') else HIST_BANNER+s

def redirect_html() -> str:
    return '''<!doctype html>
<html lang="en-GB"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>NOVA Master — moved to canonical document</title><meta http-equiv="refresh" content="0;url=./nova-master.html">
<style>body{margin:0;padding:4rem 1.5rem;background:#050914;color:#eef7ff;font:1rem/1.6 system-ui,Arial,sans-serif}
a{color:#2bdcf3}</style></head><body>
<h1>Canonical NOVA Maths Master</h1>
<p>This historical duplicate has been retired. <a href="./nova-master.html">Open the single authoritative master document</a>.</p>
<p>Use <code>node tools/export_master_prompts.js</code> to regenerate the separate portable prompts when the master changes.</p>
</body></html>
'''

def run(cmd: list[str]):
    print('RUN', ' '.join(map(str, cmd)))
    subprocess.run(cmd, cwd=str(ROOT), check=True)

def main():
    if '--check' in sys.argv:
        if not CANON.exists() or MARKER not in CANON.read_text(encoding='utf-8'):
            raise RuntimeError('Repairs not applied. Run APPLY-NOVA-REPAIRS.cmd')
        node = shutil.which('node')
        if not node: raise RuntimeError('Node.js is needed to verify the portable export')
        run([node, 'tools/export_master_prompts.js', '--check'])
        run([sys.executable, 'prompts/specs/gen.py', '--check'])
        run([sys.executable, 'tools/core_contract_audit.py'])
        print('Checks completed: canonical/sync passed. Inspect the separate core contract report for integration blockers.')
        return
    assert_baseline()
    node = shutil.which('node')
    if not node: raise RuntimeError('Node.js is required to regenerate the full portable production prompts (not available on PATH). No changes made.')
    original = CANON.read_text(encoding='utf-8')
    patched = repair_master(original)
    index_template = ROOT / 'tools' / 'templates' / 'CURRENT-docs-README.md'
    if not index_template.is_file():
        raise RuntimeError('Missing current documentation index template from repair ZIP')
    to_change = {
        CANON: patched,
        REDIRECT: redirect_html(),
        OLD_HANDOVER: historic_note(OLD_HANDOVER.read_text(encoding='utf-8')),
        ROOT / 'docs' / 'README.md': index_template.read_text(encoding='utf-8'),
    }
    for folder in [ROOT/'F2',ROOT/'F6',ROOT/'F9',ROOT/'F10']:
        if folder.exists():
            for readme in folder.glob('*README*.md'):
                if readme not in to_change:
                    to_change[readme] = historic_note(readme.read_text(encoding='utf-8'))
    # Repair currently used prompt copies; leave frozen QA reports untouched.
    for prompt in (ROOT/'prompts').rglob('*.md'):
        raw = prompt.read_text(encoding='utf-8')
        changed = raw.replace("fractions stay a neutral placeholder tagged 'fraction design TBD' until the fraction design is decided.",
                 'fractions use LOCKED traditional stacked NOVA Chalk notation, numerator above horizontal fraction bar above denominator. Do not use TBD placeholders.')
        changed = changed.replace("every fraction value uses the core placeholder (.nv-frac-tbd tagged 'fraction design TBD'); never a raw '3/4' string on stage.",
                 'every fraction displayed to learners uses traditional stacked NOVA Chalk numerator, full horizontal bar and denominator. Compact n/d only in restricted controls.')
        for token in ('assets/helpers/pip/pack80/', 'assets/helpers/nova-cat/pack60/', 'assets/helpers/teen/', 'assets/helpers/izaac/'):
            changed = changed.replace(token, 'core-native helper poses (assets/helpers/registry.json)')
        if changed != raw: to_change[prompt] = changed
    # Put pre-repair copies OUTSIDE the checkout. This doesn't pollute the next git push.
    backup = Path.home()/'NOVA-MATHS-REPAIR-BACKUPS'/datetime.now().strftime('%Y%m%d-%H%M%S')
    for file in [*to_change, PORTABLE]:
        if file.exists():
            target = backup / file.relative_to(ROOT)
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(file, target)
    applied = []
    try:
        for file, val in to_change.items():
            file.write_text(val, encoding='utf-8', newline='')
            applied.append(file)
        run([node, 'tools/export_master_prompts.js'])
        run([sys.executable, 'prompts/specs/gen.py'])
        run([sys.executable, 'tools/core_contract_audit.py'])
        run([node, 'tools/export_master_prompts.js', '--check'])
        run([sys.executable, 'prompts/specs/gen.py', '--check'])
    except Exception:
        print('ERROR: restoring modified files from safety backup')
        for file in applied+[PORTABLE]:
            saved = backup/file.relative_to(ROOT)
            if saved.exists(): shutil.copy2(saved,file)
        raise
    print('\nSUCCESS: documentation/master reconciliation applied locally ONLY.')
    print('Original copies backed up outside Git: '+str(backup))
    print('Central NOVA core and all production engine HTML files were left unchanged.')
    print('Review the core audit report before deciding on a separate runtime integration repair.')
    print('Nothing has been pushed or committed.')

if __name__ == '__main__':
    try: main()
    except Exception as error:
        print('FAILED: '+str(error), file=sys.stderr)
        sys.exit(1)
